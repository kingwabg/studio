import test from 'node:test';
import assert from 'node:assert/strict';

import { SPELL_RULES } from '../src/ui/spell-dialog.ts';

/**
 * 맞춤법 규칙 잠금 — 이 검사기의 계약은 딱 두 줄이다:
 *  ① 틀린 문장은 잡고 제안이 실제로 맞는 말이 된다
 *  ② **맞는 문장은 건드리지 않는다(오탐 0)** — 오탐 하나가 검사기 신뢰를 통째로 깎는다
 *
 * 규칙을 늘리면 아래 CLEAN 에 그 규칙이 오작동할 만한 정상 문장을 함께 넣을 것.
 */

/** 규칙 하나를 문장에 적용해 (걸렸는가, 고친 결과) 를 돌려준다 — spell-dialog 의 검사와 같은 방식 */
function applyAll(text: string): { hits: number; fixed: string } {
  let fixed = text;
  let hits = 0;
  for (const rule of SPELL_RULES) {
    rule.re.lastIndex = 0;
    const found = text.match(rule.re);
    if (!found) continue;
    hits += found.length;
    if (rule.fix != null) {
      rule.re.lastIndex = 0;
      fixed = fixed.replace(rule.re, rule.fix);
    }
  }
  return { hits, fixed };
}

/** 틀린 문장 → 고쳐진 문장 */
const CASES: Array<[string, string]> = [
  ['오늘 활동은 잘 되요.', '오늘 활동은 잘 돼요.'],
  ['교사의 역활이 중요합니다.', '교사의 역할이 중요합니다.'],
  ['참석하였읍니다.', '참석하였습니다.'],
  ['확인해 주십시요.', '확인해 주십시오.'],
  ['특이사항 없슴.', '특이사항 없음.'],
  ['이용에 참고하시기 바라며 협조를 삼가해 주시기 바랍니다.',
   '이용에 참고하시기 바라며 협조를 삼가 주시기 바랍니다.'],
  ['알맞는 자리를 배정했습니다.', '알맞은 자리를 배정했습니다.'],
  ['아동이 몇일 결석했습니다.', '아동이 며칠 결석했습니다.'],
  ['일일히 확인했습니다.', '일일이 확인했습니다.'],
  ['깨끗히 정리했습니다.', '깨끗이 정리했습니다.'],
  ['참여할수있습니다.', '참여할 수 있습니다.'],
  ['아동 및교사 대상', '아동 및 교사 대상'],
  ['프로그램및 활동', '프로그램 및 활동'],
  ['년도별 실적', '연도별 실적'],
  ['결제선을 지정하세요.', '결재선을 지정하세요.'],
  ['아동,교사 대상', '아동, 교사 대상'],
  // 문법 — 이중피동·간접높임
  ['그렇게 생각되어집니다.', '그렇게 생각됩니다.'],
  ['효과가 보여집니다.', '효과가 보입니다.'],
  ['기록이 잊혀지고 있습니다.', '기록이 잊히고 있습니다.'],
  ['둘로 나뉘어집니다.', '둘로 나뉩니다.'],
  ['원장님 말씀이 계시겠습니다.', '원장님 말씀이 있으시겠습니다.'],
  // 문장 스타일 — 번역투·군더더기·중복
  ['운영에 있어서 유의할 점', '운영에서 유의할 점'],
  ['확인하도록 하겠습니다.', '확인하겠습니다.'],
  ['과반수 이상이 찬성했습니다.', '과반수가 찬성했습니다.'],
  ['다시 재검토하겠습니다.', '재검토하겠습니다.'],
  ['매 분기마다 보고합니다.', '분기마다 보고합니다.'],
];

test('틀린 문장을 잡고 제안이 맞는 말이 된다', () => {
  for (const [bad, good] of CASES) {
    const r = applyAll(bad);
    assert.ok(r.hits > 0, `못 잡음: ${bad}`);
    assert.equal(r.fixed, good, `고친 결과가 다름: ${bad}`);
  }
});

/**
 * 오탐 0 — 아래는 전부 **맞는 문장**이다. 하나라도 걸리면 규칙을 고치지 말고 **뺀다**.
 * 특히 규칙과 글자가 겹치지만 정상인 말들을 모아 뒀다.
 */
const CLEAN = [
  '오늘 활동은 잘 됐습니다.',
  '참석하였습니다. 확인해 주십시오.',
  '특이사항 없음. 준비물 있음.',
  '결제 대금을 이체했습니다.',          // 결제(대금 지불)는 맞는 말 — 결재로 바꾸면 안 된다
  '결재를 요청했습니다.',
  '2026년도 사업계획서입니다.',          // '년도' 자체는 정상 — 년도별만 잘못
  '아동 및 교사 대상 프로그램입니다.',
  '참여할 수 있습니다. 참여할 수 없습니다.',
  '간간이 참여했습니다.',                // 간간히도 다른 뜻으로 존재 → 규칙에 넣지 않았다
  '이것과 저것은 서로 다릅니다.',
  '교사로서 최선을 다했습니다.',
  '문서로써 확인했습니다.',
  '비가 오든지 눈이 오든지 진행합니다.',
  '아이가 며칠 전에 왔습니다.',
  '삼가 고인의 명복을 빕니다.',
  '안절부절못하는 모습을 보였습니다.',
  '자료를 꼼꼼히 검토했습니다.',
  '솔직히 말씀드리면 어렵습니다.',
  '조용히 앉아 있었습니다.',
  '번번이 실패했습니다.',
  // 아래 둘은 2026-07-31 실측 오탐 — 실제 공문에서 나온 형태다. 다시 걸리면 규칙이 잘못된 것.
  '통합재정수지 2,308십억원, 사회보장성기금 1,842십억원입니다.', // 천 단위 쉼표
  '   * 사회보장성기금(4개) 현황',                                  // 개조식 들여쓰기
  // 문법·문장 규칙이 정상 문장을 물지 않는지
  '그렇게 생각됩니다. 효과가 보입니다.',
  '기록이 잊히고 있습니다. 둘로 나뉩니다.',
  '원장님 말씀이 있으시겠습니다.',
  '운영에서 유의할 점을 확인하겠습니다.',
  '협조가 필요합니다. 지원을 필요로 합니다.', // '필요로 하다'는 조사까지 바뀌어야 해 규칙에서 뺐다
  '과반수가 찬성했습니다.',
  '재검토하겠습니다. 분기마다 보고합니다.',
  '아동이 만들어진 작품을 보여 주었습니다.',   // '만들어지'는 정상 피동 — 규칙에 없다
  '문이 잘 여닫히도록 하였습니다.',
];

test('맞는 문장은 하나도 건드리지 않는다(오탐 0)', () => {
  for (const s of CLEAN) {
    const r = applyAll(s);
    assert.equal(r.hits, 0, `오탐: "${s}" → "${r.fixed}"`);
  }
});

test('종류가 붙어 있고 값이 셋 중 하나다', () => {
  for (const rule of SPELL_RULES) {
    if (rule.cat === undefined) continue; // 없으면 '철자'
    assert.ok(['철자', '문법', '문장'].includes(rule.cat), `이상한 종류: ${rule.cat}`);
  }
  // 문법·문장 규칙이 실제로 들어 있어야 한다(카테고리 배선이 죽으면 여기서 걸린다)
  assert.ok(SPELL_RULES.some((r) => r.cat === '문법'), '문법 규칙 없음');
  assert.ok(SPELL_RULES.some((r) => r.cat === '문장'), '문장 규칙 없음');
});

test('모든 규칙의 정규식에 g 플래그가 있다', () => {
  for (const rule of SPELL_RULES) {
    assert.ok(rule.re.global, `g 플래그 없음: ${rule.re}`);
  }
});
